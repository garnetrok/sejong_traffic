-- 세종 SafeRoad AI — Supabase 테이블 참고 스키마
-- 코드(web/script.html, dashboard_api.py, Python ML 파일)가 읽고 쓰는 컬럼을 바탕으로 정리한 것입니다.
-- 이미 운영 중인 DB가 있다면 그대로 두고, 새 Supabase 프로젝트를 만들 때만 SQL Editor에서 실행하세요.

-- 1) 교통사고 데이터: 대시보드(date/region/accident_type…)와 ML(legal_dong_name/occurred_year…)이 함께 사용
create table if not exists mock_accident_data (
  id                bigint generated by default as identity primary key,
  incident_no       text unique,          -- 사고번호 (중복 방지 키, 업서트 기준)
  accident_id       text,                 -- ML 집계용 사고 식별자
  date              text,                 -- 'YYYY-MM-DD'
  year              int,
  region            text,                 -- 읍/면/동
  legal_dong_name   text,                 -- 법정동명 (ML 그룹 기준)
  occurred_year     int,
  occurred_month    int,
  accident_type     text,
  occrrnc_cnt       int default 1,
  weather           text,
  day_night         text,                 -- '주간' / '야간'
  time_of_day       text,
  road_surface      text,                 -- '건조' / '젖음' / '결빙' / '적설' …
  fatalities        int default 0,
  serious_injuries  int default 0,
  spot_nm           text,
  location          text,
  status            text default '미조치', -- '미조치' / '조치중' / '완료'
  created_at        timestamptz default now()
);

-- 2) 단속 데이터
create table if not exists mock_penalty_data (
  id              bigint generated by default as identity primary key,
  date            text,
  region          text,
  violation_type  text,
  spot_nm         text,
  status          text default '미조치',
  created_at      timestamptz default now()
);

-- 3) ML 예측 결과 (save_predictions.py 가 법정동 기준으로 upsert)
create table if not exists ml_safety_scores (
  legal_dong_name              text primary key,
  predicted_quarter_accidents  double precision,
  risk_rank                    int,
  target_period                text,
  computed_at                  timestamptz default now()
);

-- 4) ML 모델 평가 기록 (save_predictions.py 가 실행마다 insert)
create table if not exists ml_model_eval (
  id             bigint generated by default as identity primary key,
  model_version  text,
  mae            double precision,
  rmse           double precision,
  r2_score       double precision,
  val_mae        double precision,
  best_params    text,
  train_rows     int,
  test_rows      int,
  train_period   text,
  test_period    text,
  created_at     timestamptz default now()
);

-- service_role 키는 RLS를 우회하므로 서버(Flask 서버)에서만 사용합니다.
alter table mock_accident_data enable row level security;
alter table mock_penalty_data  enable row level security;
alter table ml_safety_scores   enable row level security;
alter table ml_model_eval      enable row level security;
